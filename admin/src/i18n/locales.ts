export const dictionaries: Record<AdminLang, Dict> = { uk, ru, en };

export function normalizeAdminLang(value: unknown): AdminLang {
  const raw = String(value ?? '')
    .trim()
    .toLowerCase()
    .slice(0, 2);
  if (raw === 'ua') return 'uk';
  if (raw === 'ru' || raw === 'en' || raw === 'uk') return raw;
  return 'uk';
}
